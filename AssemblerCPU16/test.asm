; R0 - счетчик
; R1 - константа 50
; R8 - указатель памяти

MOV R1, 50      ; Загрузка константы (Immediate)
MOV R8, 0x100   ; Адрес в RAM
MOV R0, 0       ; Обнуляем счетчик

loop:           ; Метка начала цикла
    INC R0          ; R0++
    MOV [R8], R0    ; Сохраняем счетчик в память
    CMP R0, R1      ; R0 == 50 ?
    JZ end_prog     ; Если равно, прыгаем на выход
    JMP loop        ; Иначе повторяем

end_prog:
    HLT             ; Стоп